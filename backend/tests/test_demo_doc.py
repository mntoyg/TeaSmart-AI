"""The demo runbook must not contradict the measured evidence.

`docs/DEMO.md` is what someone reads minutes before going on stage, and it is
generated by `scripts/prepare_demo.py`. A claim there that a gate is still open,
when `docs/EVIDENCE.md` records it as passed, sends the reader to describe
working behaviour as broken plumbing.

The invariant is stated in terms of the two documents agreeing, not in terms of
any particular wording in the generator: the evidence file is read for the
parity verdict and the runbook is checked against whatever that verdict is.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
DEMO_PATH = REPO_ROOT / "docs" / "DEMO.md"
EVIDENCE_PATH = REPO_ROOT / "docs" / "EVIDENCE.md"

# Wording that tells the reader the browser/Python parity gate has yet to pass.
# Each is a distinct sentence a stale generator could emit; any one of them
# contradicts a passing verdict.
_GATE_STILL_OPEN = (
    "does not match Python's yet",
    "Known gap before step 6",
    "Until that\npasses",
    "treat an offline result as a demonstration of the plumbing",
)


@pytest.fixture(scope="module")
def demo_text() -> str:
    return DEMO_PATH.read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def evidence_text() -> str:
    return EVIDENCE_PATH.read_text(encoding="utf-8")


def _parity_verdict(evidence_text: str) -> bool:
    match = re.search(r"^passes\s+(true|false)\s*$", evidence_text, re.MULTILINE)
    assert match is not None, (
        "docs/EVIDENCE.md no longer records a `passes true|false` line for the "
        "parity gate; this test cannot check the runbook against it."
    )
    return match.group(1) == "true"


def _parity_max_delta(evidence_text: str) -> str:
    match = re.search(r"^max prob delta\s+([0-9.]+)", evidence_text, re.MULTILINE)
    assert match is not None, (
        "docs/EVIDENCE.md no longer records a `max prob delta` line for the "
        "parity gate."
    )
    return match.group(1)


def test_evidence_records_a_parity_verdict(evidence_text: str) -> None:
    """Guards the parser above: a format change must fail loudly, not silently."""
    assert _parity_verdict(evidence_text) is True


def test_runbook_does_not_call_a_passing_gate_open(
    demo_text: str, evidence_text: str
) -> None:
    if not _parity_verdict(evidence_text):
        pytest.skip("the parity gate has not passed; the runbook may say so")
    stale = [phrase for phrase in _GATE_STILL_OPEN if phrase in demo_text]
    assert not stale, (
        "docs/DEMO.md still describes the browser/Python parity gate as open "
        f"while docs/EVIDENCE.md records it as passed. Stale wording: {stale!r}. "
        "Fix the text in scripts/prepare_demo.py and regenerate."
    )


def test_runbook_cites_the_measured_parity_delta(
    demo_text: str, evidence_text: str
) -> None:
    if not _parity_verdict(evidence_text):
        pytest.skip("the parity gate has not passed; there is no delta to cite")
    delta = _parity_max_delta(evidence_text)
    assert delta in demo_text, (
        f"docs/DEMO.md does not quote the measured parity delta {delta} from "
        "docs/EVIDENCE.md, so a reader cannot tell how far inside the bound the "
        "on-device path is."
    )
